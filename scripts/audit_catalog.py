#!/usr/bin/env python3
"""Audit catalog references without guessing product identity or substituting drawings."""
import argparse
import collections
import hashlib
import json
from pathlib import Path
from urllib.parse import urljoin, urlsplit, unquote
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
BASE = 'https://exalcoaluminium.com'


def audit(root=ROOT):
    records, missing, invalid = [], [], []
    for source in sorted((root / 'data').glob('*.json')):
        try:
            data = json.loads(source.read_text(encoding='utf-8'))
        except (ValueError, OSError) as error:
            invalid.append({'file': str(source.relative_to(root)), 'error': str(error)})
            continue
        if not isinstance(data, dict):
            invalid.append({'file': str(source.relative_to(root)), 'error': 'Expected object'})
            continue
        for code, product in data.items():
            record = {'series': source.stem, 'code': code, 'assets': {},
                      'en': product.get('en', {}), 'sr': product.get('sr', {})}
            for field in ('image', 'tech_image', 'extra_images'):
                values = product.get(field) or []
                if isinstance(values, str):
                    values = [values]
                for value in values:
                    url = urljoin(BASE + '/pages/product-detail.html', value)
                    path = root / unquote(urlsplit(url).path).lstrip('/')
                    exists = urlsplit(url).netloc == 'exalcoaluminium.com' and path.is_file()
                    item = {'path': value, 'exists': exists}
                    if exists:
                        item['sha256'] = hashlib.sha256(path.read_bytes()).hexdigest()
                        item['bytes'] = path.stat().st_size
                    else:
                        missing.append({'series': source.stem, 'code': code, 'field': field, 'path': value})
                    record['assets'].setdefault(field, []).append(item)
            records.append(record)
    groups = collections.defaultdict(list)
    for record in records:
        groups[record['code']].append(record)
    sitemap = ET.parse(root / 'sitemap.xml')
    urls = [x.text for x in sitemap.findall('.//{*}loc')]
    counts = dict(collections.Counter(x['series'] for x in records))
    return {'summary': {'series': len(counts), 'records': len(records),
                        'missing_asset_references': len(missing), 'invalid_json_files': len(invalid),
                        'repeated_codes': sum(len(v) > 1 for v in groups.values()),
                        'sitemap_urls': len(urls)},
            'counts': counts, 'invalid_json': invalid, 'missing_assets': missing,
            'repeated_codes': {k: v for k, v in groups.items() if len(v) > 1},
            'policy': 'Same code, text, or image hashes are review candidates, never proof of interchangeability.'}


def write_assets(report, root=ROOT):
    missing = sorted({x['path'] for x in report['missing_assets']})
    script = ('/* Generated by scripts/audit_catalog.py --write-assets; do not guess replacement drawings. */\n'
              '(function () {\n    const missing = new Set(' + json.dumps(missing, ensure_ascii=False, indent=2) + ');\n'
              '    window.EXALCO_ASSETS = Object.freeze({\n'
              '        available: path => typeof path === "string" && path.length > 0 && !missing.has(path),\n'
              '        placeholder: "../assets/images/product-unavailable.svg"\n'
              '    });\n})();\n')
    (root / 'js/catalog-assets.js').write_text(script, encoding='utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', type=Path)
    parser.add_argument('--write-assets', action='store_true')
    parser.add_argument('--compact', action='store_true')
    args = parser.parse_args()
    report = audit()
    if args.compact:
        report['repeated_codes'] = {code: [record['series'] for record in records]
                                    for code, records in report['repeated_codes'].items()}
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    if args.write_assets:
        write_assets(report)
    print(json.dumps(report['summary'], ensure_ascii=False))
